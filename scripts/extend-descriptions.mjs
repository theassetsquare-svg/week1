let stats = { extended: 0, skipped: 0, total: 0, failed: 0 };

for (const file of dataFiles) {
  let content = fs.readFileSync(file, 'utf8');
  let modified = false;

  // 각 업소의 name, type, region, description을 순서대로 추출
  const nameMatches = [...content.matchAll(/name:'([^']+)'/g)];
  const typeMatches = [...content.matchAll(/type:'([^']+)'/g)];
  const regionMatches = [...content.matchAll(/region:'([^']+)'/g)];
  // description만 정확히 잡기 위해 앞에 공백이나 줄바꿈이 있는 것만
  const descMatches = [...content.matchAll(/(\s)description:'([^']*)'/g)];
  const idMatches = [...content.matchAll(/id:\s*(\d+)/g)];

  const count = Math.min(nameMatches.length, descMatches.length);

  for (let i = 0; i < count; i++) {
    stats.total++;
    const name = nameMatches[i][1];
    const type = typeMatches[i] ? typeMatches[i][1] : 'night';
    const region = regionMatches[i] ? regionMatches[i][1] : '';
    const desc = descMatches[i][2];
    const id = idMatches[i] ? parseInt(idMatches[i][1]) : i;

    if (desc.length >= 1000) {
      stats.skipped++;
      continue;
    }

    const needed = 1000 - desc.length + 80;

    // 전환 문장
    const trans = transitions[id % transitions.length];

    // 지역 문장
    let regionSentence = '';
    for (const [key, val] of Object.entries(regionFlavors)) {
      if (region.includes(key) || key.includes(region.replace(/서울 |부산 |경기 /g, ''))) {
        regionSentence = val;
        break;
      }
    }
    if (!regionSentence) {
      regionSentence = `${region} 지역에서 이 정도의 공간은 쉽게 찾기 어렵다. 그래서 한 번 온 사람이 다시 오는 거다.`;
    }

    // 실용 문장 선택
    const typePool = practicals[type] || practicals.night;
    const pCount = needed > 500 ? 5 : needed > 350 ? 4 : needed > 200 ? 3 : 2;
    let selected = [];
    for (let j = 0; j < pCount + 2; j++) {
      const idx = (id * (j + 3) + j * 7 + 11) % typePool.length;
      if (!selected.includes(idx)) selected.push(idx);
      if (selected.length >= pCount) break;
    }
    const practicalSentences = selected.map(idx => typePool[idx]).join(' ');

    // 마무리
    const closing = closings[(id * 3 + 1) % closings.length](name, region);

    // 조합
    const extension = ` ${trans} ${regionSentence} ${practicalSentences} ${closing}`;

    const oldStr = descMatches[i][0]; // includes leading whitespace
    const ws = descMatches[i][1]; // whitespace
    const newStr = `${ws}description:'${desc}${extension}'`;

    if (content.includes(oldStr)) {
      content = content.replace(oldStr, newStr);
      modified = true;
      stats.extended++;
    } else {
      stats.failed++;
      console.log(`⚠️ 매칭 실패: ${name}`);
    }
  }

  if (modified) {
    fs.writeFileSync(file, content, 'utf8');
    console.log(`✅ ${file} — ${count}개 처리`);
  }
}

console.log(`\n=== 결과 ===`);
console.log(`총: ${stats.total} | 확장: ${stats.extended} | 스킵: ${stats.skipped} | 실패: ${stats.failed}`);

